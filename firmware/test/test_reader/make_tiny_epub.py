"""Writes the tiny epub fixture of the reader's native tests as a C array (stored entries: the host has no inflate)."""
import io
import sys
import zipfile

container = """<?xml version="1.0"?>
<container version="1.0" xmlns="urn:oasis:names:tc:opendocument:xmlns:container">
  <rootfiles><rootfile full-path="OEBPS/content.opf" media-type="application/oebps-package+xml"/></rootfiles>
</container>"""

opf = """<?xml version="1.0" encoding="utf-8"?>
<package xmlns="http://www.idpf.org/2007/opf" version="2.0">
  <metadata xmlns:dc="http://purl.org/dc/elements/1.1/"><dc:title>Мастер &amp; Маргарита</dc:title></metadata>
  <manifest>
    <item id="css" href="style.css" media-type="text/css"/>
    <item id="c2" href="text/ch%202.xhtml" media-type="application/xhtml+xml"/>
    <item id="c1" href="text/ch1.xhtml" media-type="application/xhtml+xml"/>
    <item id="img" href="img/cover.jpg" media-type="image/jpeg"/>
  </manifest>
  <spine><itemref idref="c1"/><itemref idref="img"/><itemref idref="c2"/></spine>
</package>"""

ch1 = """<?xml version="1.0" encoding="utf-8"?>
<html xmlns="http://www.w3.org/1999/xhtml"><head><title>Глава</title><style>p{}</style></head>
<body><h1>Глава первая</h1><p>Никогда не&nbsp;разговаривайте с&#160;неизвестными&#x2026;</p>
<p>Строка<br/>вторая <img src="../img/cover.jpg"/>строка.</p><!-- a comment --></body></html>"""

ch2 = """<html><body><p>Конец.</p></body></html>"""

buf = io.BytesIO()
with zipfile.ZipFile(buf, "w", zipfile.ZIP_STORED) as z:
    z.writestr("mimetype", "application/epub+zip")
    z.writestr("META-INF/container.xml", container)
    z.writestr("OEBPS/content.opf", opf)
    z.writestr("OEBPS/text/ch1.xhtml", ch1)
    z.writestr("OEBPS/text/ch 2.xhtml", ch2)
    z.writestr("OEBPS/style.css", "p{}")
data = buf.getvalue()

out = ["// Generated by make_tiny_epub.py: a tiny epub with stored entries for the reader's tests (the host has no inflate).",
       "#pragma once", "#include <cstdint>", "", "static const uint8_t kTinyEpub[] = {"]
for i in range(0, len(data), 20):
    out.append("    " + ", ".join("0x%02x" % b for b in data[i:i + 20]) + ",")
out.append("};")
open(sys.argv[1], "w", newline="\n", encoding="utf-8").write("\n".join(out) + "\n")
print(len(data), "bytes")
