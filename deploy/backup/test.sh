#!/usr/bin/env bash
# Tries the backup scripts for real: builds the backup image, starts a throwaway PostgreSQL 17, and checks the dump,
# its rotation, the off-site copy into a local restic repository, the restore check and the failures.
#   deploy/backup/test.sh        (needs Docker; run from anywhere)
# The tables below stand in for the real schema (the API creates it): keep the backup_runs columns in step with the
# Backups migration (backend/src/Hive.Infrastructure/Data/Migrations).
set -euo pipefail
cd "$(dirname "$0")/../.."
export MSYS_NO_PATHCONV=1 # Git Bash on Windows must not rewrite /backups into a Windows path

id="$$"
net="hive-backup-test-$id"
pg="hive-backup-pg-$id"
image="village-swarm-backup:test"
failures=0

cleanup() {
	docker rm -f "$pg" >/dev/null 2>&1 || true
	docker volume rm -f "hb-backups-$id" "hb-repo-$id" "hb-media-$id" >/dev/null 2>&1 || true
	docker network rm "$net" >/dev/null 2>&1 || true
}
trap cleanup EXIT

ok() { printf '  ok   %s\n' "$1"; }
bad() { printf '  FAIL %s\n' "$1"; failures=$((failures + 1)); }
check() { # check <description> <command...>
	local what="$1"
	shift
	if "$@" >/dev/null 2>&1; then ok "$what"; else bad "$what"; fi
}

sql() { docker exec -i "$pg" psql -U hive -d hive -At -c "$1"; }
runs() { sql "SELECT count(*) FROM backup_runs WHERE kind='$1' AND ok=$2"; }
# backup <env...> -- <script>: runs one of the scripts in the image with the data volumes.
in_image() {
	local envs=()
	while [ "$1" != "--" ]; do envs+=(-e "$1"); shift; done
	shift
	docker run --rm --network "$net" -e PGHOST="$pg" -e PGPASSWORD=pw "${envs[@]}" \
		-v "hb-backups-$id:/backups" -v "hb-repo-$id:/repo" -v "hb-media-$id:/source/media:ro" "$image" "$@"
}

echo "== building the image"
docker build -q -f deploy/docker/backup.Dockerfile -t "$image" . >/dev/null

echo "== starting PostgreSQL"
docker network create "$net" >/dev/null
docker run -d --name "$pg" --network "$net" -e POSTGRES_DB=hive -e POSTGRES_USER=hive -e POSTGRES_PASSWORD=pw postgres:17 >/dev/null
for _ in $(seq 1 40); do docker exec "$pg" pg_isready -U hive -d hive -q && break; sleep 1; done
sleep 2
sql "CREATE TABLE devices (id serial PRIMARY KEY, device_id text);
     CREATE TABLE events (id serial PRIMARY KEY, type text);
     CREATE TABLE backup_runs (id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, kind varchar(16) NOT NULL,
         started_at timestamptz NOT NULL, finished_at timestamptz NOT NULL, ok boolean NOT NULL, bytes bigint, detail varchar(512));
     INSERT INTO devices (device_id) SELECT 'meteo-' || g FROM generate_series(1, 3) g;
     INSERT INTO events (type) SELECT 'motion' FROM generate_series(1, 20);" >/dev/null
docker volume create "hb-media-$id" >/dev/null
docker run --rm -v "hb-media-$id:/m" alpine sh -c 'mkdir -p /m/2026/10 && echo photo > /m/2026/10/a.jpg' >/dev/null

echo "== dump and restore check, no off-site copy"
check "backup.sh succeeds" in_image BACKUP_KEEP=2 -- backup.sh
[ "$(runs dump true)" = "1" ] && ok "a dump run is in the journal" || bad "a dump run is in the journal"
[ "$(sql "SELECT bytes > 0 FROM backup_runs WHERE kind='dump'")" = "t" ] && ok "the dump has a size" || bad "the dump has a size"
check "verify.sh succeeds" in_image -- verify.sh
[ "$(runs verify true)" = "1" ] && ok "a verify run is in the journal" || bad "a verify run is in the journal"
[ "$(sql "SELECT detail FROM backup_runs WHERE kind='verify'")" = "restored $(docker run --rm -v "hb-backups-$id:/backups" alpine sh -c 'ls /backups/db | head -1'): 3 devices, 20 events" ] \
	&& ok "verify counted the restored rows" || bad "verify counted the restored rows ($(sql "SELECT detail FROM backup_runs WHERE kind='verify'"))"
[ "$(docker exec "$pg" psql -U hive -d postgres -At -c "SELECT count(*) FROM pg_database WHERE datname LIKE 'hive_verify_%'")" = "0" ] \
	&& ok "the scratch database is gone" || bad "the scratch database is gone"

echo "== rotation"
sleep 1; in_image BACKUP_KEEP=2 -- backup.sh >/dev/null
sleep 1; in_image BACKUP_KEEP=2 -- backup.sh >/dev/null
[ "$(docker run --rm -v "hb-backups-$id:/backups" alpine sh -c 'ls /backups/db | wc -l')" = "2" ] && ok "only the newest 2 dumps stay" || bad "only the newest 2 dumps stay"

echo "== off-site copy into a local restic repository"
check "backup.sh with a repository succeeds" in_image RESTIC_REPOSITORY=/repo RESTIC_PASSWORD=secret -- backup.sh
[ "$(runs offsite true)" = "1" ] && ok "an offsite run is in the journal" || bad "an offsite run is in the journal"
listing="$(in_image RESTIC_REPOSITORY=/repo RESTIC_PASSWORD=secret -- restic ls latest 2>&1 || true)"
printf '%s' "$listing" | grep -q "a.jpg" && ok "the photos are in the snapshot" || bad "the photos are in the snapshot"
printf '%s' "$listing" | grep -q "hive-.*\.dump" && ok "the dump is in the snapshot" || bad "the dump is in the snapshot"
check "verify.sh with a repository succeeds" in_image RESTIC_REPOSITORY=/repo RESTIC_PASSWORD=secret -- verify.sh
[ "$(sql "SELECT count(*) FROM backup_runs WHERE kind='verify' AND ok AND detail LIKE '%off-site repository checked%'")" = "1" ] \
	&& ok "verify read the repository" || bad "verify read the repository"

echo "== failures are recorded, not hidden"
if in_image RESTIC_REPOSITORY=/repo -- backup.sh >/dev/null 2>&1; then bad "a missing repository password fails the run"; else ok "a missing repository password fails the run"; fi
[ "$(runs offsite false)" = "1" ] && ok "the failed off-site run is in the journal" || bad "the failed off-site run is in the journal"
docker run --rm -v "hb-backups-$id:/backups" alpine sh -c 'for f in /backups/db/*.dump; do head -c 300 "$f" > "$f.cut"; mv "$f.cut" "$f"; done'
if in_image -- verify.sh >/dev/null 2>&1; then bad "a damaged dump fails the restore check"; else ok "a damaged dump fails the restore check"; fi
[ "$(runs verify false)" = "1" ] && ok "the failed check is in the journal" || bad "the failed check is in the journal"
[ "$(docker exec "$pg" psql -U hive -d postgres -At -c "SELECT count(*) FROM pg_database WHERE datname LIKE 'hive_verify_%'")" = "0" ] \
	&& ok "the scratch database is gone after a failure too" || bad "the scratch database is gone after a failure too"

echo
if [ "$failures" -eq 0 ]; then echo "All backup checks passed."; else echo "$failures check(s) failed."; exit 1; fi
